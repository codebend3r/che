def update(*, check_only: bool = False, dry_run: bool = False) -> int:
    """Pull the latest scripts, then refresh whatever is installed.

    This is the "update the app itself" path: it moves the repo forward, then
    re-runs the install with the recorded settings so new commands get wrappers
    without the user having to remember a second step.

    Only a git clone can be moved forward from here. A copy installed from npm
    has no ``.git``, so it is told the npm command instead of a confusing
    ``git fetch failed``.
    """
    colors = palette()
    if not is_git_checkout():
        warning("❌ This copy of che is not a git checkout, so `che update` cannot pull it.")
        note(f"   Update it with `{update_command()}`, then `che install` to refresh the wrappers.")
        return 1
    if not shutil.which("git"):
        warning("❌ git is not installed, so che cannot update itself.")
        return 1

    info("Fetching…")
    if run(["git", "fetch", "--prune"], cwd=REPO, check=False).returncode != 0:
        warning("❌ git fetch failed.")
        return 1

    # Empty when the branch has no upstream or HEAD is detached: git explains
    # on stderr and prints nothing.
    count = run_output(["git", "rev-list", "--count", "HEAD..@{upstream}"], check=False, cwd=REPO)

    if not count:
        warning("❌ The checked-out branch has no upstream to pull from.")
        note("   Check out a branch that tracks origin, usually main, then run `che update` again.")
        return 1
    if check_only:
        if count == "0":
            success("Already up to date.")
        else:
            note(f"{count} commit(s) available. Run `che update` to apply.")
        return 0

    python = require_python()
    if python is None:
        return 1
    if count == "0":
        success("Already up to date.")
    elif not _pull(count, dry_run=dry_run):
        return 1

    record = load_record()
    if record is None:
        note("che is not installed yet; running the installer.")
        return wizard(InstallPlan(shells=default_shell_selection(), python=python, dry_run=dry_run))

    print()
    status = run_install(InstallPlan.from_record(record, python=python, dry_run=dry_run))

    print()
    success("Updated. Reload your shell to pick up new commands:")
    print(f"  {colors.bold}exec {login_shell() or 'zsh'}{colors.reset}")
    return status


def _pull(count: str, *, dry_run: bool) -> bool:
    """Fast-forward the clone by its ``count`` new commits, then list them."""
    if has_tracked_changes(REPO):
        warning("❌ The repo has uncommitted changes; not pulling.")
        note("   Commit or stash them, then run `che update` again.")
        return False
    if dry_run:
        note(f"would pull {count} commit(s)")
        return True

    before = run_output(["git", "rev-parse", "HEAD"], check=False, cwd=REPO)
    if run(["git", "pull", "--ff-only"], cwd=REPO, check=False).returncode != 0:
        warning("❌ git pull --ff-only failed - the branch has diverged.")
        return False

    colors = palette()
    print()
    note("What changed:")
    log = run_output(
        ["git", "log", "--oneline", "--no-decorate", f"{before}..HEAD"], check=False, cwd=REPO
    )
    for line in log.splitlines()[:20]:
        print(f"  {colors.grey}{line}{colors.reset}")
    return True


def uninstall(*, dry_run: bool = False, purge: bool = False) -> int:
    """Take out what ``che install`` put in: the rc blocks, the shim and the record.

    ``purge`` also deletes the whole config directory, backups included, and
    the state directory, which holds the menu's per-prompt input history.
    """
    removed = phrase("removed", dry_run=dry_run)
    touched = False

    for spec in SHELLS.values():
        for rc_file in spec.rc_files:
            original = read_rc(rc_file)
            if commit_rc(rc_file, original, without_block(original), dry_run=dry_run):
                touched = True
                print(f"  {mark()} {removed} block from {tildify(rc_file)}")

    leftovers = [config_dir(), state_dir()] if purge else [config_file()]
    if is_che_shim(shim_path()):
        leftovers.insert(0, shim_path())
    for path in leftovers:
        if not path.exists():
            continue
        touched = True
        if not dry_run:
            if path.is_dir():
                shutil.rmtree(path)
            else:
                path.unlink()
        print(f"  {mark()} {removed} {tildify(path)}")

    if not touched:
        note("Nothing to remove - che was not installed here.")
    elif dry_run:
        print()
        note("Dry run: nothing was removed.")
    else:
        print()
        success("Uninstalled. The repo itself is untouched; delete it to finish.")
    return 0


