def wizard(plan: InstallPlan, *, install_deps: bool = False) -> int:
    """Walk a first-time user through the whole setup.

    ``plan`` is what is already decided. It preselects the shells, and a
    question it already answers - ``--no-sounds``, ``--no-path-shim``,
    ``--replace-legacy`` or ``install_deps`` - is not asked again.
    """
    colors = palette()
    print_logo(f"shell helpers, v{VERSION} - first-run setup")

    version = python_version(plan.python) or ()
    print(f"  {mark()} python {version_text(version)}  {colors.grey}{plan.python}{colors.reset}")
    print(f"  {mark()} repo    {colors.grey}{REPO}{colors.reset}")
    print(f"  {mark()} {len(all_commands())} commands ready to wrap")
    print()

    shells = _ask_shells(plan.shells)
    if not shells:
        warning("Nothing selected - install cancelled.")
        return 1

    print()
    path_shim = plan.path_shim and confirm(
        f"Add a `che` command to {tildify(shim_path())} so scripts and cron can call it?",
        default=True,
    )
    sounds = plan.sounds and confirm(
        "Play the playsound-N chime when a command finishes?", default=True
    )
    replace_legacy = plan.replace_legacy or _ask_legacy(shells)
    install_deps = install_deps or _ask_tools()
    plan = replace(
        plan, shells=shells, path_shim=path_shim, sounds=sounds, replace_legacy=replace_legacy
    )

    print()
    status = run_install(plan, install_deps=install_deps)

    print()
    success("Done. Start using it with:")
    print(
        f"  {colors.bold}exec {shells[0]}{colors.reset}   {colors.grey}(reload your shell){colors.reset}"
    )
    print(
        f"  {colors.bold}che{colors.reset}          {colors.grey}(browse every command){colors.reset}"
    )
    print(
        f"  {colors.bold}che doctor{colors.reset}   {colors.grey}(check the install){colors.reset}"
    )
    return status


def _ask_shells(preselected: list[str]) -> list[str]:
    """The shells to install into: those present on this machine, ``preselected`` ticked."""
    specs = list(SHELLS.values())
    selectable = [spec for spec in specs if spec.installed or spec.has_rc] or [SHELLS["zsh"]]
    picked = choose(
        "Which shells should che install into?",
        [
            (
                spec.name + ("  (your login shell)" if spec.is_login_shell else ""),
                ", ".join(tildify(path) for path in spec.rc_files),
            )
            for spec in selectable
        ],
        selected=[index for index, spec in enumerate(selectable) if spec.name in preselected],
    )
    return [selectable[index].name for index in picked]


def _ask_legacy(shells: list[str]) -> bool:
    """Whether to replace the hand-written wrappers in ``shells``' rc files, if any."""
    found = {
        rc_file: names
        for shell in shells
        for rc_file in SHELLS[shell].rc_files
        if (names := find_legacy(read_rc(rc_file)))
    }
    if not found:
        return False

    colors = palette()
    print()
    total = sum(len(names) for names in found.values())
    note(f"Found {total} hand-written wrappers from before che managed them:")
    for rc_file, names in found.items():
        print(
            f"  {colors.grey}{rc_file}: {', '.join(names[:6])}"
            f"{'…' if len(names) > 6 else ''}{colors.reset}"
        )
    return confirm(
        "Replace them with the generated ones? (a backup is written first)", default=True
    )


def _ask_tools() -> bool:
    """Whether to install the missing external tools, after listing them."""
    missing = missing_binaries()
    if not missing:
        return False

    colors = palette()
    print()
    note(f"Missing external tools: {', '.join(missing)}")
    for name in missing:
        hint = INSTALL_HINTS.get(name)
        if hint:
            print(f"  {colors.grey}{name}: {hint}{colors.reset}")
    return bool(shutil.which("brew")) and confirm("Install them now with Homebrew?", default=False)


