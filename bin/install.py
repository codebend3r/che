#!/usr/bin/env python3
"""Install the ``che`` wrappers into the shells this machine actually has.

Run it directly on a fresh machine::

    python3 bin/install.py            # first-run wizard
    python3 bin/install.py --yes      # same, no questions asked

or, once the wrappers exist, through the dispatcher: ``che install``,
``che update``, ``che uninstall``. The machine facts this reads are in
``machine.py``, the rc-file edits in ``rcfile.py``, and ``che doctor``, which
checks the result, in ``doctor.py``.

What "installed" means here is deliberately small. A few lines go into the
user's rc file between two markers this script owns: where the repo is, which
python to use, whether to chime, the line that puts the ``che`` shim on PATH,
and the line that sources the generated wrapper file. Everything else (the
wrappers themselves, the completions) lives in the repo and is regenerated
from ``bin/commands.py``, so upgrading never rewrites the user's dotfiles.

Unlike the destructive scripts under ``bin/<category>/``, this one does NOT
default to dry-run: it is the entry point that creates the wrappers, so
defaulting to "change nothing" would leave a first-time user with nothing
installed and no obvious reason why. ``--dry-run`` is still there, and every
rc file it edits is backed up first.
"""

