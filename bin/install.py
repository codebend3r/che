def build_install_parser() -> BoolFlagParser:
    parser = build_parser(
        prog="che install",
        description="📥 Install the che shell wrappers into your shell startup files.",
        epilog=(
            "Examples:\n"
            "  che install                        interactive first-run wizard\n"
            "  che install --yes                  install into the detected shells\n"
            "  che install --shells=zsh,fish      pick the shells yourself\n"
            "  che install --dry-run              show what would change\n"
            "  che install --replace-legacy       drop hand-written wrappers first\n"
            "  che install --print                print the rc block and exit"
        ),
    )
    parser.add_argument(
        "--shells",
        default="",
        metavar="LIST",
        help="Comma-separated: zsh, bash, fish, sh (default: detected)",
    )
    add_bool_flag(parser, "--all-shells", help="Install into every shell present on this machine")
    add_bool_flag(parser, "--yes", help="Skip the wizard and use the defaults")
    add_bool_flag(parser, "--dry-run", help="Report what would change, change nothing")
    # Accepted and ignored: the completions load with the wrappers and cannot
    # be left out. Hidden, but kept so an existing `--no-completions` still runs.
    add_bool_flag(
        parser,
        "--no-completions",
        allow_value=False,
        help=argparse.SUPPRESS,
    )
    add_bool_flag(
        parser,
        "--no-path-shim",
        allow_value=False,
        help="Do not put a `che` executable in ~/.local/bin",
    )
    add_bool_flag(
        parser,
        "--no-sounds",
        allow_value=False,
        help="Do not call playsound-N when a command finishes",
    )
    add_bool_flag(
        parser,
        "--replace-legacy",
        help="Remove hand-written wrappers this repo now generates",
    )
    add_bool_flag(
        parser,
        "--install-deps",
        help="Install missing external tools with Homebrew",
    )
    add_bool_flag(parser, "--print", dest="print_block", help="Print the rc block and exit")
    return parser


def install_main(argv: list[str] | None = None) -> int:
    args = build_install_parser().parse_args(argv)

    shells = _requested_shells(args)
    if shells is None:
        return 1
    python = require_python()
    if python is None:
        return 1

    plan = InstallPlan(
        shells=shells,
        python=python,
        sounds=not args.no_sounds,
        path_shim=not args.no_path_shim,
        replace_legacy=args.replace_legacy,
        dry_run=args.dry_run,
    )

    if args.print_block:
        for shell in plan.shells:
            print(block_for(shell, plan), end="")
        return 0

    if not args.yes and not args.shells and not args.all_shells and is_interactive():
        return wizard(plan, install_deps=args.install_deps)

    print_logo(f"installing che {VERSION}")
    status = run_install(plan, install_deps=args.install_deps)

    print()
    success("Reload your shell to pick up the wrappers:  exec " + (login_shell() or "zsh"))
    return status


def _requested_shells(args: argparse.Namespace) -> list[str] | None:
    """The shells the flags ask for, or None, said why, when one is unknown."""
    if args.all_shells:
        return [spec.name for spec in SHELLS.values() if spec.installed and not spec.opt_in]
    if args.shells:
        requested = [part.strip() for part in args.shells.split(",") if part.strip()]
        unknown = [name for name in requested if name not in SHELLS]
        if unknown:
            warning(f"❌ Unknown shell(s): {', '.join(unknown)}")
            note(f"   Known: {', '.join(SHELLS)}")
            return None
        return requested
    return default_shell_selection()


def update_main(argv: list[str] | None = None) -> int:
    parser = build_parser(
        prog="che update", description="⬆️  Update the scripts, then refresh the wrappers."
    )
    add_bool_flag(parser, "--check", help="Report whether an update is available, apply nothing")
    add_bool_flag(parser, "--dry-run", help="Report what would change, change nothing")
    args = parser.parse_args(argv)
    return update(check_only=args.check, dry_run=args.dry_run)


def uninstall_main(argv: list[str] | None = None) -> int:
    parser = build_parser(
        prog="che uninstall", description="🧽 Remove the wrappers, shim and completions."
    )
    add_bool_flag(parser, "--dry-run", help="Report what would change, change nothing")
    add_bool_flag(parser, "--purge", help="Also delete ~/.config/che and the menu's history")
    args = parser.parse_args(argv)
    return uninstall(dry_run=args.dry_run, purge=args.purge)


if __name__ == "__main__":
    run_cli(install_main)
