@dataclass
class InstallPlan:
    shells: list[str]
    python: str
    sounds: bool = True
    path_shim: bool = True
    replace_legacy: bool = False
    dry_run: bool = False

    def to_record(self, rc_files: list[Path]) -> InstallRecord:
        """What ``config.json`` keeps, so ``che update`` can repeat this install."""
        return InstallRecord(
            version=VERSION,
            home=str(REPO),
            python=self.python,
            shells=self.shells,
            rc_files=[str(path) for path in rc_files],
            sounds=self.sounds,
            path_shim=self.path_shim,
            installed_at=datetime.now().isoformat(timespec="seconds"),
        )

    @classmethod
    def from_record(cls, record: InstallRecord, *, python: str, dry_run: bool) -> InstallPlan:
        """The plan that repeats a recorded install under ``python``."""
        return cls(
            shells=list(record.shells),
            python=python,
            sounds=record.sounds,
            path_shim=record.path_shim,
            dry_run=dry_run,
        )


@dataclass
class InstallResult:
    rc_actions: list[tuple[Path, str]] = field(default_factory=list)
    generated: list[Path] = field(default_factory=list)
    legacy_removed: dict[Path, list[str]] = field(default_factory=dict)
    shim: str = "skipped"


def block_for(shell: str, plan: InstallPlan) -> str:
    """The rc block ``plan`` writes for ``shell``, and so what ``--print`` shows."""
    return shellgen.rc_block(
        SHELLS[shell].flavor,
        home=REPO,
        python=plan.python,
        sounds=plan.sounds,
        path_dir=shim_path().parent if plan.path_shim else None,
    )


def perform_install(plan: InstallPlan) -> InstallResult:
    """Do the install described by ``plan``. No prompting happens here."""
    result = InstallResult()
    try:
        result.generated = shellgen.sync_generated(dry_run=plan.dry_run)
    except ValueError as exc:
        # The README lost a marker. The committed shell/ files still work, so
        # the rc blocks that point at them can still be written.
        warning(f"❌ {exc}")

    for shell in plan.shells:
        spec = SHELLS.get(shell)
        if spec is None:
            warning(f"❌ Unknown shell: {shell}")
            continue

        block = block_for(shell, plan)
        for rc_file in spec.rc_files:
            original = text = read_rc(rc_file)
            if plan.replace_legacy:
                text, removed = without_legacy(text)
                if removed:
                    result.legacy_removed[rc_file] = removed
            updated, action = with_block(text, block)
            commit_rc(rc_file, original, updated, dry_run=plan.dry_run)
            result.rc_actions.append((rc_file, action))

    if plan.path_shim:
        result.shim = install_shim(plan.python, dry_run=plan.dry_run)

    save_record(plan.to_record([path for path, _ in result.rc_actions]), dry_run=plan.dry_run)
    return result


def run_install(plan: InstallPlan, *, install_deps: bool = False) -> int:
    """Install, say what happened, then fetch the missing tools when asked to.

    Returns the exit status: 1 when a tool the user asked for did not install.
    """
    report(plan, perform_install(plan))
    missing = missing_binaries() if install_deps else []
    if not missing:
        return 0
    print()
    return 0 if install_missing_binaries(missing, dry_run=plan.dry_run) else 1


def require_python() -> str | None:
    """The interpreter the wrappers will run, or None, said why, when none is new enough.

    Writing a too-old one into every rc block would break every wrapper at once.
    """
    python, version = find_python()
    if python_ok(version):
        return python
    warning(f"❌ Python {MIN_PYTHON_TEXT}+ is required (found {version_text(version)}).")
    note(f"   Install one with `{PYTHON_HINT}`, then run this again.")
    return None


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------

# Past tense for what happened, present tense for what a dry run would do.
DRY_VERB = {
    "created": "create",
    "updated": "update",
    "unchanged": "leave unchanged",
    "installed": "install",
    "removed": "remove",
    "regenerated": "regenerate",
}


def phrase(action: str, *, dry_run: bool) -> str:
    """``action`` as done, or as what a dry run would do."""
    if not dry_run:
        return action
    colors = palette()
    return f"{colors.yellow}would {DRY_VERB.get(action, action)}{colors.reset}"


def mark(action: str = "") -> str:
    """What starts a report line: a grey ``=`` for something left alone, else a ``✓``."""
    colors = palette()
    if action == "unchanged":
        return f"{colors.grey}={colors.reset}"
    return f"{colors.green}✓{colors.reset}"


def report(plan: InstallPlan, result: InstallResult) -> None:
    """Print what an install did, in the same shape for wizard and --yes."""
    colors = palette()
    dry_run = plan.dry_run

    for rc_file, action in result.rc_actions:
        print(f"  {mark(action)} {phrase(action, dry_run=dry_run)} block in {tildify(rc_file)}")

    for rc_file, names in result.legacy_removed.items():
        print(
            f"  {mark()} {phrase('removed', dry_run=dry_run)} "
            f"{len(names)} legacy wrappers from {tildify(rc_file)}"
        )

    if result.generated:
        print(
            f"  {mark()} {phrase('regenerated', dry_run=dry_run)} "
            f"{len(result.generated)} files under shell/"
        )

    if plan.path_shim:
        print(
            f"  {mark(result.shim)} che shim {phrase(result.shim, dry_run=dry_run)}: "
            f"{tildify(shim_path())}"
        )
        if not shim_on_path():
            print(
                f"  {colors.grey}  ({shim_path().parent} is added to PATH by the block){colors.reset}"
            )


