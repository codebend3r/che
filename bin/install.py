SHIM_HEADER = "# Generated by `che install`"


def install_shim(python: str, *, dry_run: bool = False) -> str:
    """Put a ``che`` executable on PATH, for use outside an interactive shell.

    The shell function is what a human types; this shim is what a cron job, a
    Makefile or another script can call, none of which source an rc file.

    A ``che`` that is a symlink is never written through. With an npm prefix of
    ``~/.local``, ``npm install -g`` links it straight to ``bin/che.py``, and
    writing through that link would replace the dispatcher with a shim that
    execs itself. A link to this repo's dispatcher already does the shim's job;
    any other link is replaced, not followed.
    """
    target = shim_path()
    dispatcher = REPO / "bin" / "che.py"
    script = (
        "#!/bin/sh\n"
        f"{SHIM_HEADER} (che {VERSION}). Do not edit.\n"
        f'exec {json.dumps(python)} {json.dumps(str(dispatcher))} "$@"\n'
    )

    if target.is_symlink():
        if target.resolve() == dispatcher.resolve():
            return "unchanged"
        if not dry_run:
            target.unlink()
    elif target.exists() and target.read_text(encoding="utf-8", errors="replace") == script:
        return "unchanged"
    if not dry_run:
        atomic_write_text(target, script, mode=0o755)
    return "installed"


def is_che_shim(path: Path) -> bool:
    """Whether ``path`` is a shim ``che install`` wrote, not a link or a stranger's file."""
    return (
        not path.is_symlink()
        and path.is_file()
        and SHIM_HEADER in path.read_text(encoding="utf-8", errors="replace")
    )


def install_missing_binaries(names: list[str], *, dry_run: bool = False) -> bool:
    """Install missing tools with Homebrew. Returns whether every one went in."""
    formulae = sorted({BREW_FORMULA[name] for name in names if name in BREW_FORMULA})
    if not formulae:
        return True
    if not shutil.which("brew"):
        warning("❌ Homebrew is not installed; install the tools yourself:")
        for name in names:
            note(f"   {INSTALL_HINTS.get(name, name)}")
        return False

    info(f"Installing: {' '.join(formulae)}")
    if dry_run:
        return True
    result = run(["brew", "install", *formulae], check=False)
    return result.returncode == 0


